-- M3 shape scale and the 9-piece rounded rectangles used by every Tonic shape.
-- Fills: one white circle texture per size, tinted with SetVertexColor; its four
-- quadrants are the corners and its center row/column stretch into edges and fill.
-- Outlines: ring quadrants for the corners plus four 1-texel bars. No blur, no masks.

local T = Tonic

---@class TonicShape
local Shape = {
	-- Corner radii in dp. "full" resolves to half the shorter side.
	tokens = {
		none = 0,
		xs = 4,      -- snackbar
		s = 8,       -- auras, chips
		m = 12,      -- slots, menus
		ml = 14,     -- rich tooltips
		l = 16,      -- HUD panels
		xl = 28,     -- windows, minimap
		full = "full", -- bars, buttons, toolbars
	},
	-- Generated by tools/tokens: Circle<size>.tga, quadrant = size / 2 pixels.
	circleSizes = { 16, 32, 64, 128 },
	-- Ring<ratio>.tga: stroke as a percentage of the outer radius.
	ringRatios = { 3, 6, 10, 15, 20, 30 },
	shadowTexture = T.mediaPath .. "Textures\\Shadow64",
	white = "Interface\\Buttons\\WHITE8X8",
}
T.Shape = Shape

local min, max, floor, abs = math.min, math.max, math.floor, math.abs

---Resolves a shape token or a radius in dp to a corner radius in UI units of region,
---snapped to pixels and never more than half the shorter side.
---@param shape string|number
---@param region Region
---@param width number UI units
---@param height number UI units
---@return number
function Shape:Radius(shape, region, width, height)
	local r = type(shape) == "number" and shape or self.tokens[shape] or 0
	local px = T.Scale:PixelSize(region)
	local half = floor(min(width, height) / 2 / px) * px
	if r == "full" then return half end
	if r <= 0 then return 0 end
	return min(T.Scale:Dp(r, region), half)
end

---Picks the smallest circle texture whose quadrant covers the corner in pixels.
---@param cornerPixels number
---@return string
function Shape:CircleTexture(cornerPixels)
	local sizes = self.circleSizes
	for i = 1, #sizes do
		if sizes[i] / 2 >= cornerPixels then
			return T.mediaPath .. "Textures\\Circle" .. sizes[i]
		end
	end
	return T.mediaPath .. "Textures\\Circle" .. sizes[#sizes]
end

---Picks the ring texture whose stroke ratio is closest to stroke / corner.
---@param cornerPixels number
---@param strokePixels number
---@return string
function Shape:RingTexture(cornerPixels, strokePixels)
	local wanted = cornerPixels > 0 and strokePixels / cornerPixels * 100 or 100
	local best, bestDiff = self.ringRatios[1], math.huge
	for _, ratio in ipairs(self.ringRatios) do
		local diff = abs(ratio - wanted)
		if diff < bestDiff then best, bestDiff = ratio, diff end
	end
	return T.mediaPath .. "Textures\\Ring" .. best
end

-- ------------------------------------------------------------- fill pieces

-- Piece order: TL, T, TR, L, C, R, BL, B, BR. Tex coords: left, right, top, bottom.
local COORDS = {
	{ 0, 0.5, 0, 0.5 }, { 0.5, 0.5, 0, 0.5 }, { 0.5, 1, 0, 0.5 },
	{ 0, 0.5, 0.5, 0.5 }, { 0.5, 0.5, 0.5, 0.5 }, { 0.5, 1, 0.5, 0.5 },
	{ 0, 0.5, 0.5, 1 }, { 0.5, 0.5, 0.5, 1 }, { 0.5, 1, 0.5, 1 },
}
local SOLID = { 0.5, 0.5, 0.5, 0.5 }
local CORNERS = { 1, 3, 7, 9 }

---@class TonicShapePieces
---@field owner Frame
---@field textures Texture[]
---@field file string?
---@field corner number?
---@field shown boolean
local PiecesMixin = {}

---Lays out the pieces around the owner.
---@param corner number corner size in UI units (already snapped)
---@param file string texture path
---@param left number outset in UI units (positive grows the shape)
---@param top number
---@param right number
---@param bottom number
---@param squareBottom? boolean bottom corners stay square (filled text fields, tab indicators)
function PiecesMixin:Layout(corner, file, left, top, right, bottom, squareBottom)
	local t = self.textures
	if file ~= self.file then
		self.file = file
		for i = 1, 9 do t[i]:SetTexture(file, "CLAMP", "CLAMP", "LINEAR") end
	end
	if squareBottom ~= self.squareBottom then
		self.squareBottom = squareBottom
		t[7]:SetTexCoord(unpack(squareBottom and SOLID or COORDS[7]))
		t[9]:SetTexCoord(unpack(squareBottom and SOLID or COORDS[9]))
	end
	for _, i in ipairs(CORNERS) do t[i]:SetSize(corner, corner) end
	local o = self.owner
	t[1]:SetPoint("TOPLEFT", o, "TOPLEFT", -left, top)
	t[3]:SetPoint("TOPRIGHT", o, "TOPRIGHT", right, top)
	t[7]:SetPoint("BOTTOMLEFT", o, "BOTTOMLEFT", -left, -bottom)
	t[9]:SetPoint("BOTTOMRIGHT", o, "BOTTOMRIGHT", right, -bottom)
	-- Zero-sized corners still anchor the edges.
	self.corner = corner
	local visible = self.shown and corner > 0
	for _, i in ipairs(CORNERS) do t[i]:SetShown(visible) end
end

---@param r number
---@param g number
---@param b number
---@param a? number
function PiecesMixin:SetColor(r, g, b, a)
	for i = 1, 9 do self.textures[i]:SetVertexColor(r, g, b, a or 1) end
end

---@param shown boolean
function PiecesMixin:SetShown(shown)
	self.shown = shown
	local cornersVisible = shown and (self.corner or 0) > 0
	for i = 1, 9 do
		local isCorner = i == 1 or i == 3 or i == 7 or i == 9
		self.textures[i]:SetShown(isCorner and cornersVisible or (not isCorner and shown))
	end
end

---Creates the 9 textures of a filled shape on owner.
---@param owner Frame
---@param layer DrawLayer
---@param sublevel integer
---@return TonicShapePieces
function Shape:CreatePieces(owner, layer, sublevel)
	local p = CreateFromMixins(PiecesMixin)
	p.owner = owner
	p.textures = {}
	local t = p.textures
	for i = 1, 9 do
		t[i] = owner:CreateTexture(nil, layer, nil, sublevel)
		t[i]:SetTexCoord(unpack(COORDS[i]))
	end
	-- Edges and fill stretch between the corners; these anchors never change.
	t[2]:SetPoint("TOPLEFT", t[1], "TOPRIGHT"); t[2]:SetPoint("BOTTOMRIGHT", t[3], "BOTTOMLEFT")
	t[4]:SetPoint("TOPLEFT", t[1], "BOTTOMLEFT"); t[4]:SetPoint("BOTTOMRIGHT", t[7], "TOPRIGHT")
	t[5]:SetPoint("TOPLEFT", t[1], "BOTTOMRIGHT"); t[5]:SetPoint("BOTTOMRIGHT", t[9], "TOPLEFT")
	t[6]:SetPoint("TOPLEFT", t[3], "BOTTOMLEFT"); t[6]:SetPoint("BOTTOMRIGHT", t[9], "TOPRIGHT")
	t[8]:SetPoint("TOPLEFT", t[7], "TOPRIGHT"); t[8]:SetPoint("BOTTOMRIGHT", t[9], "BOTTOMLEFT")
	p.shown = true
	return p
end

---Lays out fill pieces on region for a shape token, with an optional inset in dp.
---@param pieces TonicShapePieces
---@param region Region
---@param shape string|number
---@param insetDp? number
---@param squareBottom? boolean
---@return number radius UI units
function Shape:Apply(pieces, region, shape, insetDp, squareBottom)
	local width, height = region:GetSize()
	if width <= 0 or height <= 0 then return 0 end
	local inset = insetDp and insetDp ~= 0 and T.Scale:Dp(insetDp, region) or 0
	local radius = max(self:Radius(shape, region, width, height) - inset, 0)
	local px = T.Scale:PixelSize(region)
	pieces:Layout(radius, self:CircleTexture(radius / px), -inset, -inset, -inset, -inset, squareBottom)
	return radius
end

-- ------------------------------------------------------------- outline pieces

---@class TonicShapeOutline
---@field owner Frame
---@field corners Texture[] TL, TR, BL, BR
---@field bars Texture[] top, bottom, left, right
local OutlineMixin = {}

local CORNER_COORDS = { { 0, 0.5, 0, 0.5 }, { 0.5, 1, 0, 0.5 }, { 0, 0.5, 0.5, 1 }, { 0.5, 1, 0.5, 1 } }

---@param corner number UI units
---@param stroke number UI units
---@param file string ring texture
function OutlineMixin:Layout(corner, stroke, file)
	local c, b, o = self.corners, self.bars, self.owner
	if file ~= self.file then
		self.file = file
		for i = 1, 4 do c[i]:SetTexture(file, "CLAMP", "CLAMP", "LINEAR") end
	end
	for i = 1, 4 do c[i]:SetSize(corner, corner) end
	c[1]:SetPoint("TOPLEFT", o, "TOPLEFT")
	c[2]:SetPoint("TOPRIGHT", o, "TOPRIGHT")
	c[3]:SetPoint("BOTTOMLEFT", o, "BOTTOMLEFT")
	c[4]:SetPoint("BOTTOMRIGHT", o, "BOTTOMRIGHT")
	b[1]:SetHeight(stroke); b[2]:SetHeight(stroke)
	b[3]:SetWidth(stroke); b[4]:SetWidth(stroke)
	self.corner = corner
	self:SetShown(self.shown)
end

function OutlineMixin:SetColor(r, g, b, a)
	for i = 1, 4 do
		self.corners[i]:SetVertexColor(r, g, b, a or 1)
		self.bars[i]:SetVertexColor(r, g, b, a or 1)
	end
end

function OutlineMixin:SetShown(shown)
	self.shown = shown
	local cornersVisible = shown and (self.corner or 0) > 0
	for i = 1, 4 do
		self.corners[i]:SetShown(cornersVisible)
		self.bars[i]:SetShown(shown)
	end
end

---Creates a stroke-only rounded rectangle on owner (drawn inside its bounds).
---@param owner Frame
---@param layer DrawLayer
---@param sublevel integer
---@return TonicShapeOutline
function Shape:CreateOutline(owner, layer, sublevel)
	local o = CreateFromMixins(OutlineMixin)
	o.owner = owner
	o.corners, o.bars = {}, {}
	for i = 1, 4 do
		o.corners[i] = owner:CreateTexture(nil, layer, nil, sublevel)
		o.corners[i]:SetTexCoord(unpack(CORNER_COORDS[i]))
		o.bars[i] = owner:CreateTexture(nil, layer, nil, sublevel)
		o.bars[i]:SetTexture(self.white)
	end
	local c, b = o.corners, o.bars
	b[1]:SetPoint("TOPLEFT", c[1], "TOPRIGHT"); b[1]:SetPoint("TOPRIGHT", c[2], "TOPLEFT")
	b[2]:SetPoint("BOTTOMLEFT", c[3], "BOTTOMRIGHT"); b[2]:SetPoint("BOTTOMRIGHT", c[4], "BOTTOMLEFT")
	b[3]:SetPoint("TOPLEFT", c[1], "BOTTOMLEFT"); b[3]:SetPoint("BOTTOMLEFT", c[3], "TOPLEFT")
	b[4]:SetPoint("TOPRIGHT", c[2], "BOTTOMRIGHT"); b[4]:SetPoint("BOTTOMRIGHT", c[4], "TOPRIGHT")
	o.shown = true
	return o
end

---Lays out an outline on region for a shape token.
---@param outline TonicShapeOutline
---@param region Region
---@param shape string|number
---@param strokeDp? number default 1
function Shape:ApplyOutline(outline, region, shape, strokeDp)
	local width, height = region:GetSize()
	if width <= 0 or height <= 0 then return end
	local px = T.Scale:PixelSize(region)
	local stroke = T.Scale:Dp(strokeDp or 1, region)
	local radius = self:Radius(shape, region, width, height)
	outline:Layout(radius, stroke, self:RingTexture(radius / px, stroke / px))
end
