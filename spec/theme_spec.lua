local wow = require("spec.helpers.wow")

describe("Theme", function()
	local T

	before_each(function()
		T = wow.LoadAddon()
	end)

	it("uses the class of the character as seed", function()
		assert.are.equal("MAGE", T.Theme:GetTheme().seed)
		assert.are.equal("3FC7EB", T.Scheme:GetSeedHex("MAGE"))
	end)

	it("matches the reference tokens for the mage", function()
		-- test/tonic-tokens.json: mago.dark.primary = #86d1ea
		local theme = T.Theme:Build("MAGE", "dark")
		assert.are.equal("86D1EA", T.Color.ToHex(theme:Color("primary")))
	end)

	it("falls back to DEFAULT for unknown seeds", function()
		assert.are.equal("DEFAULT", T.Theme:Build("NOPE", "dark").seed)
		wow.class = "NOPE"
		assert.are.equal("DEFAULT", T.Theme:GetSeed())
	end)

	it("resolves roles, elevation names and semantic tokens", function()
		local theme = T.Theme:Build("MAGE", "dark")
		assert.are.same(theme.roles.surfaceContainerLow, theme:Color("window"))
		assert.are.same(theme.roles.surfaceContainerHighest, theme:Color("highest"))
		assert.are.same(theme.semantic.health.bar, theme:Color("health.bar"))
		assert.are.same({ 1, 1, 1 }, theme:Color("missing"))
		assert.are.equal(1, #wow.errors)
	end)

	it("pushes changes to registered objects", function()
		local received
		T.Theme:Register({ ApplyTheme = function(_, theme) received = theme end })
		assert.are.equal("dark", received.mode)
		T.Theme:SetMode("light")
		assert.are.equal("light", received.mode)
	end)

	it("clamps the HUD opacity", function()
		T.Theme:SetHudOpacity(0.2)
		assert.are.equal(0.60, T.db.profile.theme.hudOpacity)
		T.Theme:SetHudOpacity(1.5)
		assert.are.equal(1.00, T.Theme:GetTheme().hudOpacity)
	end)

	it("keeps common item quality neutral", function()
		local theme = T.Theme:Build("DRUID", "dark")
		local c = theme:Color("qualityCommon.color")
		assert.is_true(math.max(c[1], c[2], c[3]) - math.min(c[1], c[2], c[3]) < 0.12)
	end)

	it("can keep health unharmonized", function()
		local harmonized = T.Theme:Build("DRUID", "dark"):Color("health.bar")
		T.db.profile.theme.harmonizeHealth = false
		local theme = T.Theme:Build("DRUID", "dark")
		assert.are.same(theme.semantic.healthBase.bar, theme:Color("health.bar"))
		assert.is_false(harmonized == theme:Color("health.bar"))
		assert.are.same(theme.semantic.mana.bar, theme:Color("mana.bar"))
	end)

	it("shows dev as version of an unpackaged checkout", function()
		assert.are.equal("dev", T.version)
	end)

	it("mixes state layers", function()
		local mixed = T.Color.Mix({ 0, 0, 0 }, { 1, 1, 1 }, T.Color.STATE.hover)
		assert.are.same({ 0.08, 0.08, 0.08 }, mixed)
	end)
end)

describe("Gallery smoke test", function()
	it("builds and toggles without errors, in both modes", function()
		local T = wow.LoadAddon()
		SlashCmdList.TONIC("gallery")
		local gallery = T:GetModule("Gallery")
		assert.is_not_nil(gallery.window)
		assert.are.equal(2, #gallery.columns)
		gallery:CycleSeed(1)
		SlashCmdList.TONIC("mode light")
		SlashCmdList.TONIC("seed druid")
		SlashCmdList.TONIC("opacity 0,7")
		SlashCmdList.TONIC("gallery")
		assert.is_false(gallery.window:IsShown())
		assert.are.same({}, wow.errors)
	end)

	it("releases surfaces and texts back to their pools", function()
		local T = wow.LoadAddon()
		local parent = CreateFrame("Frame")
		local surfaces, texts = T.Surface.pool:GetNumActive(), T.Text.pool:GetNumActive()
		local s = T.Surface:Acquire(parent, { usage = "menu", width = 100, height = 40 })
		local t = T.Text:Acquire(s, { text = "x" })
		t:Release()
		s:Release()
		assert.are.equal(surfaces, T.Surface.pool:GetNumActive())
		assert.are.equal(texts, T.Text.pool:GetNumActive())
	end)
end)
